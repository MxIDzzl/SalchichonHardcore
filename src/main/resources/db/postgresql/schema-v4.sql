-- PostgreSQL schema v4: auditable manual adjustments to the Player Value aggregate.
-- This ledger records administrative corrections separately from item-backed vault value.

CREATE TABLE IF NOT EXISTS player_value_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_uuid UUID NOT NULL REFERENCES player_data(uuid),
    previous_value BIGINT NOT NULL CHECK (previous_value >= 0),
    new_value BIGINT NOT NULL CHECK (new_value >= 0),
    adjustment_delta BIGINT NOT NULL,
    actor VARCHAR(64) NOT NULL,
    reason TEXT NOT NULL CHECK (length(trim(reason)) > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_player_value_adjustments_player
    ON player_value_adjustments (player_uuid, created_at, id);
