-- PostgreSQL schema v1 for SalchichonHardcore.
-- Apply only after backing up hardcore.db and validating the migration plan.
-- UUIDs are stored as native UUID values. All timestamps are UTC timestamptz.

CREATE TABLE IF NOT EXISTS schema_version (
    version INTEGER PRIMARY KEY,
    applied_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS player_data (
    uuid UUID PRIMARY KEY,
    username VARCHAR(16) NOT NULL,
    last_death_date DATE,
    totem_uses BIGINT NOT NULL DEFAULT 0 CHECK (totem_uses >= 0)
);

CREATE TABLE IF NOT EXISTS admin_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_uuid UUID NOT NULL,
    target_name VARCHAR(16) NOT NULL,
    admin_name VARCHAR(64) NOT NULL,
    action VARCHAR(64) NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_admin_audit_target_created
    ON admin_audit (target_uuid, created_at DESC);

-- Official, admin-correctable counters are separate from vanilla client statistics.
CREATE TABLE IF NOT EXISTS player_stats (
    player_uuid UUID PRIMARY KEY REFERENCES player_data(uuid) ON DELETE CASCADE,
    official_deaths BIGINT NOT NULL DEFAULT 0 CHECK (official_deaths >= 0),
    playtime_ticks BIGINT NOT NULL DEFAULT 0 CHECK (playtime_ticks >= 0),
    player_value BIGINT NOT NULL DEFAULT 0 CHECK (player_value >= 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Append-only audit trail for changes to official statistics.
CREATE TABLE IF NOT EXISTS stat_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_uuid UUID NOT NULL REFERENCES player_data(uuid) ON DELETE CASCADE,
    stat_key VARCHAR(64) NOT NULL,
    previous_value BIGINT NOT NULL,
    new_value BIGINT NOT NULL,
    actor VARCHAR(64) NOT NULL,
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_stat_events_player_created
    ON stat_events (player_uuid, created_at DESC);
